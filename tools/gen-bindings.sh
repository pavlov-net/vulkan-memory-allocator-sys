#!/usr/bin/env bash
# Regenerates src/bindings.rs from src/vma.h and vendor/. The headers are parsed for x86_64 Linux
# on every host, so the output doesn't depend on the host. Needs clang (CLANG, else clang on
# PATH, else the default LLVM install on Windows). Installs the pinned bindgen-cli into
# target/tools on first use, or set BINDGEN to use another copy of that version.
set -euo pipefail

bindgen_version=0.73.2

root="$(cd "$(dirname "$0")/.." && pwd)"
out="$root/src/bindings.rs"

bindgen="${BINDGEN:-}"
if [ -z "$bindgen" ]; then
  bindgen_root="$root/target/tools/bindgen-cli-$bindgen_version"
  bindgen="$bindgen_root/bin/bindgen"
  if [ ! -x "$bindgen" ] && [ ! -x "$bindgen.exe" ]; then
    cargo install --quiet --locked --root "$bindgen_root" bindgen-cli --version "$bindgen_version"
  fi
fi

clang="${CLANG:-clang}"
if ! command -v "$clang" > /dev/null && [ -x "/c/Program Files/LLVM/bin/clang.exe" ]; then
  clang="/c/Program Files/LLVM/bin/clang.exe"
fi

resource_dir="$("$clang" -print-resource-dir)"

vma_version="$(sed -n 's/^#define VMA_VERSION (VK_MAKE_VERSION(\([0-9]*\), \([0-9]*\), \([0-9]*\)))/\1.\2.\3/p' \
  "$root/vendor/VulkanMemoryAllocator/include/vk_mem_alloc.h")"
if [ -z "$vma_version" ]; then
  echo "no VMA_VERSION in vk_mem_alloc.h" >&2
  exit 1
fi

"$bindgen" "$root/src/vma.h" \
  --rust-target 1.85 \
  --rust-edition 2024 \
  --use-core \
  --allowlist-function 'vma.*' \
  --allowlist-type 'Vma.*' \
  --default-enum-style consts \
  --no-prepend-enum-name \
  --with-derive-default \
  --no-layout-tests \
  --no-doc-comments \
  --formatter prettyplease \
  --raw-line "// Generated by tools/gen-bindings.sh from VulkanMemoryAllocator $vma_version. Do not edit." \
  -o "$out.tmp" \
  -- \
  --target=x86_64-unknown-linux-gnu -ffreestanding \
  -isystem "$resource_dir/include" \
  -I "$root/vendor/VulkanMemoryAllocator/include" \
  -I "$root/vendor/Vulkan-Headers/include"
tr -d '\r' < "$out.tmp" > "$out"
rm "$out.tmp"
echo "bindings in $out"
